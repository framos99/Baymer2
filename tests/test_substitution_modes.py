"""End-to-end fits under the substitution and recurrence likelihoods.

These are the tests that justify the modes existing. Data is simulated
from a known branch process with real multiple hits; the binomial is
expected to understate the rate, and the CTMC to recover it.
"""

from __future__ import annotations

import numpy as np
import pytest

from baymer2.backends.numba_mh import LayerConfig
from baymer2.contexts import ContextTree
from baymer2.counts import CountTable
from baymer2.likelihoods.ctmc import CTMCLikelihood, build_qmap
from baymer2.model import ModelConfig, fit


def _layer_config(iterations: int = 4000, **kw) -> LayerConfig:
    base = dict(
        n_iterations=iterations,
        burnin=iterations // 2,
        thin=5,
        set_sigma=0.85,
        c=0.04472136,
        phi_proposal_sd=0.05,
    )
    base.update(kw)
    return LayerConfig(**base)


def simulate_branch(tree: ContextTree, true_rates: np.ndarray, n_per_context: int,
                    rng, branch_length: float = 1.0) -> CountTable:
    """Counts generated by an actual CTMC run along the branch."""
    layer = tree.n_layers - 1
    _, _, slot_base = build_qmap(tree, layer)
    lik = CTMCLikelihood(tree, branch_length=branch_length)

    n = tree.layer_size(layer)
    counts = np.zeros((n, 4))
    for i in range(n):
        p = lik.transition_matrix(true_rates, i, layer=layer)
        ancestral = slot_base[i, 0]
        draws = rng.multinomial(n_per_context, p[ancestral])
        for s in range(4):
            counts[i, s] = draws[slot_base[i, s]]
    return CountTable(tree=tree, leaf_counts=counts, name="sim")


