@pytest.mark.parametrize("likelihood", ["binomial", "recurrent", "ctmc"])
def test_every_mode_fits_a_centred_tree(likelihood):
    tree = ContextTree(max_mer=3, growth="centred")
    rng = np.random.default_rng(0)
    counts = np.zeros((tree.n_leaves, 4))
    counts[:, 0] = 100_000
    counts[:, 1:] = rng.integers(200, 2000, size=(tree.n_leaves, 3))
    table = CountTable(tree=tree, leaf_counts=counts, name="sim")

    cfg = ModelConfig(max_mer=3, growth="centred", likelihood=likelihood,
                      seed=1, default_layer=_layer_config(1500))
    result = fit(table, cfg)
    assert len(result.layers) == tree.n_layers
    for layer in range(tree.n_layers):
        rates = result.rates(layer)
        assert np.all(np.isfinite(rates))
        assert np.all(rates > 0)


def test_ctmc_fit_is_reproducible():
    tree = ContextTree(max_mer=3, growth="centred")
    rng = np.random.default_rng(1)
    counts = np.zeros((tree.n_leaves, 4))
    counts[:, 0] = 50_000
    counts[:, 1:] = rng.integers(500, 3000, size=(tree.n_leaves, 3))
    table = CountTable(tree=tree, leaf_counts=counts)
    cfg = ModelConfig(max_mer=3, growth="centred", likelihood="ctmc", seed=7,
                      default_layer=_layer_config(800))
    a = fit(table, cfg)
    b = fit(table, cfg)
    np.testing.assert_array_equal(a.rates(1), b.rates(1))


# --------------------------------------------------------------------------
# The claim: multiple hits bias the binomial, CTMC corrects it
# --------------------------------------------------------------------------


@pytest.mark.slow
def test_ctmc_recovers_rates_the_binomial_understates():
    """Simulate a long branch, fit both ways, compare against truth."""
    tree = ContextTree(max_mer=3, growth="centred")
    layer = tree.n_layers - 1
    n = tree.layer_size(layer)
    rng = np.random.default_rng(23)

    # Rates high enough that multiple hits genuinely accumulate.
    true_rates = rng.uniform(0.03, 0.09, size=(n, 3))
    table = simulate_branch(tree, true_rates, 400_000, rng)

    common = dict(max_mer=3, growth="centred", seed=5,
                  default_layer=_layer_config(6000, phi_proposal_sd=0.03))
    ctmc = fit(table, ModelConfig(likelihood="ctmc", **common)).rates(layer)
    binomial = fit(table, ModelConfig(likelihood="binomial", **common)).rates(layer)

    ctmc_err = np.median(np.abs(ctmc - true_rates) / true_rates)
    binom_err = np.median(np.abs(binomial - true_rates) / true_rates)

    # The binomial must be biased low: it reads apparent divergence as rate.
    assert np.median(binomial / true_rates) < 0.97, (
        "binomial should understate rates when multiple hits occur"
    )
    assert ctmc_err < binom_err / 2.0, (
        f"ctmc median error {ctmc_err:.4f} should be well below binomial "
        f"{binom_err:.4f}"
    )
    assert ctmc_err < 0.05


@pytest.mark.slow
def test_ctmc_and_binomial_agree_on_a_short_branch():
    """No multiple hits, no correction: the modes must coincide."""
    tree = ContextTree(max_mer=3, growth="centred")
    layer = tree.n_layers - 1
    n = tree.layer_size(layer)
    rng = np.random.default_rng(31)

    true_rates = rng.uniform(1e-4, 5e-4, size=(n, 3))
    table = simulate_branch(tree, true_rates, 20_000_000, rng)

    common = dict(max_mer=3, growth="centred", seed=3,
                  default_layer=_layer_config(4000, phi_proposal_sd=0.03))
    ctmc = fit(table, ModelConfig(likelihood="ctmc", **common)).rates(layer)
    binomial = fit(table, ModelConfig(likelihood="binomial", **common)).rates(layer)

    np.testing.assert_allclose(ctmc, binomial, rtol=0.05)
    np.testing.assert_allclose(ctmc, true_rates, rtol=0.10)


@pytest.mark.slow
def test_the_ctmc_correction_is_largest_at_hypermutable_contexts():
    """Saturation is rate-dependent, so the correction must be too.

    On real data the CTMC raises CpG rates more than others, but there
    the mechanism is inferred. Here CpG contexts are *given* a tenfold
    rate and the claim is checked under control: the binomial's shortfall
    must grow with the true rate, because a faster context saturates
    sooner.
    """
    tree = ContextTree(max_mer=3, growth="centred")
    layer = tree.n_layers - 1
    contexts = tree.contexts(layer)
    n = tree.layer_size(layer)
    rng = np.random.default_rng(101)

    cpg = np.array([c[1:] == "CG" for c in contexts])
    true_rates = rng.uniform(0.010, 0.020, size=(n, 3))
    true_rates[cpg] *= 10.0  # hypermutable, as CpG really is

    table = simulate_branch(tree, true_rates, 400_000, rng)

    common = dict(max_mer=3, growth="centred", seed=11,
                  default_layer=_layer_config(6000, phi_proposal_sd=0.03))
    ctmc = fit(table, ModelConfig(likelihood="ctmc", **common)).rates(layer)
    binomial = fit(table, ModelConfig(likelihood="binomial", **common)).rates(layer)

    binom_shortfall = 1.0 - binomial.sum(axis=1) / true_rates.sum(axis=1)
    ctmc_shortfall = 1.0 - ctmc.sum(axis=1) / true_rates.sum(axis=1)

    # The binomial understates the fast contexts far more than the slow.
    assert binom_shortfall[cpg].mean() > binom_shortfall[~cpg].mean() + 0.05, (
        f"binomial shortfall: CpG {binom_shortfall[cpg].mean():.3f} vs "
        f"other {binom_shortfall[~cpg].mean():.3f}"
    )
    # The CTMC removes that dependence.
    assert abs(ctmc_shortfall[cpg].mean()) < 0.05
    assert abs(ctmc_shortfall[~cpg].mean()) < 0.05

    # And so the binomial compresses the elevation while the CTMC keeps it.
    true_elev = true_rates[cpg].sum(axis=1).mean() / true_rates[~cpg].sum(axis=1).mean()
    binom_elev = binomial[cpg].sum(axis=1).mean() / binomial[~cpg].sum(axis=1).mean()
    ctmc_elev = ctmc[cpg].sum(axis=1).mean() / ctmc[~cpg].sum(axis=1).mean()
    assert binom_elev < true_elev * 0.92, (
        f"binomial elevation {binom_elev:.2f} should fall well short of the "
        f"true {true_elev:.2f}"
    )
    assert ctmc_elev == pytest.approx(true_elev, rel=0.06)
