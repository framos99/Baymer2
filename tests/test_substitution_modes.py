def test_ctmc_refuses_the_alternating_tree():
    tree = ContextTree(max_mer=5)
    table = CountTable(tree=tree, leaf_counts=np.ones((tree.n_leaves, 4)))
    cfg = ModelConfig(max_mer=5, likelihood="ctmc",
                      default_layer=_layer_config(200))
    with pytest.raises(ValueError, match="reverse-complement closed"):
        fit(table, cfg)


def test_growth_mismatch_is_caught():
    tree = ContextTree(max_mer=3, growth="centred")
    table = CountTable(tree=tree, leaf_counts=np.ones((tree.n_leaves, 4)))
    with pytest.raises(ValueError, match="growth"):
        fit(table, ModelConfig(max_mer=3, default_layer=_layer_config(200)))


