"""The CTMC likelihood must reduce to the binomial and beat it on truth.

Two things are being checked. First, that the machinery is right:
``expm4`` against scipy, the assembled ``Q`` against hand-built rate
matrices, row stochasticity. Second, that the *point* holds -- when data
is generated by a branch process with real multiple hits, the binomial
underestimates the rate and the CTMC recovers it.
"""

from __future__ import annotations

import numpy as np
import pytest
from scipy.linalg import expm as scipy_expm

from baymer2.contexts import BASE_INDEX, BASES, ContextTree, alt_bases, reverse_complement
from baymer2.likelihoods.binomial import BinomialLikelihood
from baymer2.likelihoods.ctmc import CTMCLikelihood, build_qmap, expm4


def _expm4(a: np.ndarray) -> np.ndarray:
    out = np.zeros((4, 4))
    expm4(np.ascontiguousarray(a, dtype=np.float64), out)
    return out


# --------------------------------------------------------------------------
# Matrix exponential
# --------------------------------------------------------------------------


@pytest.mark.parametrize("scale", [1e-8, 1e-4, 1e-2, 0.1, 1.0, 5.0, 20.0])
def test_expm4_matches_scipy(scale):
    rng = np.random.default_rng(0)
    for _ in range(20):
        q = rng.uniform(0, 1, size=(4, 4)) * scale
        np.fill_diagonal(q, 0.0)
        np.fill_diagonal(q, -q.sum(axis=1))
        np.testing.assert_allclose(_expm4(q), scipy_expm(q), rtol=1e-10, atol=1e-13)


def test_expm4_of_zero_is_identity():
    np.testing.assert_allclose(_expm4(np.zeros((4, 4))), np.eye(4), atol=1e-15)


def test_expm_of_a_rate_matrix_is_row_stochastic():
    rng = np.random.default_rng(1)
    for _ in range(50):
        q = rng.uniform(0, 2, size=(4, 4))
        np.fill_diagonal(q, 0.0)
        np.fill_diagonal(q, -q.sum(axis=1))
        p = _expm4(q)
        np.testing.assert_allclose(p.sum(axis=1), 1.0, rtol=1e-12)
        assert np.all(p >= 0.0)


