@pytest.mark.parametrize("k", [1, 3, 5])
def test_qmap_builds_for_centred_contexts(k):
    tree = ContextTree(max_mer=k)
    q_src, q_slot, slot_base = build_qmap(tree, k - 1)
    n = tree.layer_size(k - 1)
    assert q_src.shape == (n, 4, 4)
    off_diagonal = ~np.eye(4, dtype=bool)
    assert np.all(q_src[:, off_diagonal] >= 0)
    assert np.all(q_slot[:, off_diagonal] >= 0)
    assert np.all(np.diagonal(q_src, axis1=1, axis2=2) == -1)


@pytest.mark.parametrize("k", [2, 4])
def test_qmap_refuses_off_centre_contexts(k):
    tree = ContextTree(max_mer=k)
    with pytest.raises(ValueError, match="centred focal base"):
        build_qmap(tree, k - 1)


def test_qmap_resolves_rates_to_the_right_context():
    """A G>A rate must be read as the C>T rate of the reverse complement."""
    tree = ContextTree(max_mer=3)
    contexts = tree.contexts(2)
    index = {c: i for i, c in enumerate(contexts)}
    q_src, q_slot, _ = build_qmap(tree, 2)

    i = index["AAA"]  # flanks A_A
    g, a = BASE_INDEX["G"], BASE_INDEX["A"]
    # Substituting G gives AGA, whose reverse complement is TCT.
    assert contexts[q_src[i, g, a]] == "TCT"
    # G>A on this strand is C>T on the other.
    assert alt_bases("C")[q_slot[i, g, a]] == "T"


def test_qmap_slot_bases_follow_the_count_convention():
    tree = ContextTree(max_mer=3)
    _, _, slot_base = build_qmap(tree, 2)
    for i, ctx in enumerate(tree.contexts(2)):
        focal = ctx[1]
        assert slot_base[i, 0] == BASE_INDEX[focal]
        for s, b in enumerate(alt_bases(focal), start=1):
            assert slot_base[i, s] == BASE_INDEX[b]


def test_quartets_are_closed():
    """Every node's Q sources must themselves resolve to the same group."""
    tree = ContextTree(max_mer=3)
    q_src, _, _ = build_qmap(tree, 2)
    n = q_src.shape[0]
    off = ~np.eye(4, dtype=bool)
    for i in range(n):
        group = set(q_src[i][off].tolist()) | {i}
        for member in group:
            assert set(q_src[member][off].tolist()) | {member} == group


