def test_transition_matrix_is_stochastic():
    tree = ContextTree(max_mer=3)
    n = tree.layer_size(2)
    rng = np.random.default_rng(5)
    rates = rng.uniform(1e-3, 5e-2, size=(n, 3))
    lik = CTMCLikelihood(tree, branch_length=2.0)
    for node in (0, 7, 31):
        p = lik.transition_matrix(rates, node, layer=2)
        np.testing.assert_allclose(p.sum(axis=1), 1.0, rtol=1e-12)
        assert np.all(p > 0.0)


def test_same_flanks_share_one_generator():
    """Q depends only on the flanks, so F[A] and F[C] must share it.

    They are different sites -- different ancestral base -- but the
    instantaneous rates around them are the same, which is exactly what
    makes the quartet a single 4x4 rather than four unrelated rows.
    """
    tree = ContextTree(max_mer=3)
    contexts = tree.contexts(2)
    index = {c: i for i, c in enumerate(contexts)}
    rng = np.random.default_rng(6)
    rates = rng.uniform(1e-3, 2e-2, size=(len(contexts), 3))
    lik = CTMCLikelihood(tree, branch_length=1.0)

    for left in "ACGT":
        for right in "ACGT":
            i = index[left + "A" + right]
            j = index[left + "C" + right]
            np.testing.assert_allclose(
                lik.transition_matrix(rates, i, layer=2),
                lik.transition_matrix(rates, j, layer=2),
                rtol=1e-12,
                err_msg=f"flanks {left}_{right}",
            )


def test_reverse_complement_partner_has_the_permuted_generator():
    """Q at revcomp-partner flanks equals Q complement-permuted.

    Node ``F_L A F_R`` and node ``revcomp(F_R) A revcomp(F_L)`` describe
    the two strands of the same physical neighbourhood, so their
    generators must agree after complementing both source and target.
    """
    tree = ContextTree(max_mer=3)
    contexts = tree.contexts(2)
    index = {c: i for i, c in enumerate(contexts)}
    rng = np.random.default_rng(6)
    rates = rng.uniform(1e-3, 2e-2, size=(len(contexts), 3))
    lik = CTMCLikelihood(tree, branch_length=1.0)

    for left in "ACGT":
        for right in "ACGT":
            i = index[left + "A" + right]
            partner = reverse_complement(right) + "A" + reverse_complement(left)
            j = index[partner]
            pi = lik.transition_matrix(rates, i, layer=2)
            pj = lik.transition_matrix(rates, j, layer=2)
            for a in BASES:
                for b in BASES:
                    lhs = pi[BASE_INDEX[a], BASE_INDEX[b]]
                    rhs = pj[
                        BASE_INDEX[reverse_complement(a)],
                        BASE_INDEX[reverse_complement(b)],
                    ]
                    assert lhs == pytest.approx(rhs, rel=1e-9), (left, right, a, b)


# --------------------------------------------------------------------------
# The scientific claim: multiple hits bias the binomial
# --------------------------------------------------------------------------


def test_binomial_underestimates_divergence_where_ctmc_does_not():
    """Simulate a real branch process and compare recovered rates.

    Sites evolve under a known Q for time t. The apparent divergence
    (what the binomial reads as the rate) must fall short of the true
    Q*t, and the CTMC's implied transition probabilities must match the
    simulation.
    """
    rng = np.random.default_rng(11)
    # A single context's generator, deliberately fast so hits accumulate.
    q = np.array([
        [0.0, 0.10, 0.30, 0.05],
        [0.12, 0.0, 0.06, 0.28],
        [0.30, 0.05, 0.0, 0.11],
        [0.04, 0.31, 0.09, 0.0],
    ])
    np.fill_diagonal(q, -q.sum(axis=1))
    t = 2.0
    p_true = scipy_expm(q * t)

    n_sites = 400_000
    ancestral = 0  # 'A'
    observed = rng.choice(4, size=n_sites, p=p_true[ancestral])
    counts = np.bincount(observed, minlength=4).astype(float)

    apparent = 1.0 - counts[ancestral] / n_sites
    expected_true = -q[ancestral, ancestral] * t

    assert apparent < expected_true, (
        "multiple hits must make apparent divergence fall short of Q*t"
    )
    # Empirical transition frequencies must match exp(Qt), which is what
    # the CTMC likelihood models and the binomial does not.
    np.testing.assert_allclose(counts / n_sites, p_true[ancestral], atol=0.005)


def test_ctmc_likelihood_is_maximised_near_the_generating_rates():
    """A coarse profile check: truth beats scaled-away alternatives."""
    tree = ContextTree(max_mer=1)
    q_src, q_slot, slot_base = build_qmap(tree, 0)
    n = tree.layer_size(0)

    rng = np.random.default_rng(13)
    true_rates = np.array([[0.05, 0.12, 0.03], [0.04, 0.02, 0.15]])
    lik = CTMCLikelihood(tree, branch_length=1.0)

    stats = np.zeros((n, 4))
    for i in range(n):
        p = lik.transition_matrix(true_rates, i, layer=0)
        anc = slot_base[i, 0]
        draws = rng.multinomial(1_000_000, p[anc])
        for s in range(4):
            stats[i, s] = draws[slot_base[i, s]]

    best = lik.log_likelihood(stats, true_rates, layer=0).sum()
    for factor in (0.7, 0.85, 1.15, 1.4):
        worse = lik.log_likelihood(stats, true_rates * factor, layer=0).sum()
        assert worse < best, f"scaling rates by {factor} should not improve fit"
